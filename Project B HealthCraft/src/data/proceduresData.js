export function getProcedureBySlug(slugOrPath) {
  if (!slugOrPath) return null;
  const clean = slugOrPath.toLowerCase().replace(/^\/+|\/+$/g, '').trim();

  // 1. Direct key match
  if (PROCEDURES_DATA[clean]) {
    return PROCEDURES_DATA[clean];
  }

  // 2. Exact match in altSlugs or slug
  for (const proc of Object.values(PROCEDURES_DATA)) {
    if (proc.slug === clean) return proc;
    if (proc.altSlugs && proc.altSlugs.includes(clean)) return proc;
  }

  // 3. Partial normalized match (without -in-pune or -pune)
  const normalized = clean.replace(/-in-pune$/, '').replace(/-pune$/, '');
  for (const proc of Object.values(PROCEDURES_DATA)) {
    const procNorm = proc.slug.replace(/-in-pune$/, '').replace(/-pune$/, '');
    if (procNorm === normalized) return proc;
    if (proc.altSlugs && proc.altSlugs.some(s => s.replace(/-in-pune$/, '').replace(/-pune$/, '') === normalized)) {
      return proc;
    }
  }

  return null;
}
